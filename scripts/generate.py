#!/usr/bin/env python3
"""Generate the Rule and each harness's own files in the workspace, from the core, modules and workspace.

Sources: AGENTS.md (core, then each enabled module), rules/house-rules.md, agents/ (assembled like
`korrigans agent`), skills/ (every layer), mcp/servers.toml (merged across layers).
Files written in the workspace (never edit them by hand):
  AGENTS.md                                                     the Rule, read by every harness
  .agents/skills/<name>                                         links to each skill (workspace skills win)
  CLAUDE.md, .claude/agents/*.md, .claude/skills, .claude/settings.json, .mcp.json      Claude Code
  .pi/mcp.json                                                  pi
  .codex/config.toml                                            Codex
  state/hermes.yaml                                             Hermes (merge into ~/.hermes/config.yaml)

    korrigans generate              generate everything
    korrigans generate --check      report extensions missing from extensions/registry.toml, write nothing
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

WS = common.WS
CLAUDE_TOOLS = {
    "read": ["Read", "Grep", "Glob"],
    "write": ["Edit", "Write"],
    "shell": ["Bash"],
    "web": ["WebSearch", "WebFetch"],
}
WARNING = "Generated by `korrigans generate`; do not edit by hand."


def write(rel, text):
    path = WS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"  {rel}")


def body(path):
    """Text of a markdown file without its frontmatter."""
    return common.split_frontmatter(path.read_text(encoding="utf-8"))[1].strip()


def generate_rule():
    parts = [f"<!-- {WARNING} Your own rules go in rules/house-rules.md, then run `korrigans generate`. -->"]
    core_rule = common.CORE / "AGENTS.md"
    if core_rule.exists():
        parts.append(body(core_rule))
    for m in common.modules():
        fragment = common.CORE / "modules" / m / "AGENTS.md"
        if fragment.exists():
            parts.append(body(fragment))
    house = WS / "rules" / "house-rules.md"
    if house.exists():
        text = re.sub(r"^# .*\n+", "", body(house) + "\n").strip()
        if text:
            parts.append("## House rules\n\nSet by the user. They add to the rules above and never lift one of them.\n\n"
                         + text)
    if common.language_line():
        parts.append(common.language_line())
    write("AGENTS.md", "\n\n".join(parts) + "\n")


def skills():
    """{name: skill dir} over every layer; a workspace skill wins over a module or core one."""
    return {n: p for n, p in common.list_names("skills").items() if p.is_dir() and (p / "SKILL.md").exists()}


def link_skills(found):
    folder = WS / ".agents" / "skills"
    folder.mkdir(parents=True, exist_ok=True)
    for entry in sorted(folder.iterdir()):
        if entry.is_symlink() and (entry.name not in found or Path(os.readlink(entry)) != found[entry.name]):
            entry.unlink()
    for name, path in found.items():
        link = folder / name
        if link.is_symlink():
            continue
        if link.exists():
            print(f"  ! .agents/skills/{name} is a real folder, left as it is (it hides the skill of the same name)")
            continue
        link.symlink_to(path, target_is_directory=True)
    print(f"  .agents/skills/ ({len(found)} skills)")


def mcp_json(servers, with_type):
    result = {}
    for name, s in servers.items():
        if "url" in s:
            result[name] = ({"type": "http"} if with_type else {}) | {"url": s["url"]}
        else:
            result[name] = {"command": s["command"], "args": s.get("args", [])}
            if s.get("env"):
                result[name]["env"] = s["env"]
    return result


def generate_claude(harness, servers):
    write("CLAUDE.md", f"<!-- {WARNING} -->\n@AGENTS.md\n")
    models = harness.get("claude", {}).get("models", {})
    folder = WS / ".claude" / "agents"
    for old in folder.glob("*.md") if folder.exists() else []:
        if WARNING in old.read_text(encoding="utf-8"):
            old.unlink()
    for agent, _ in common.list_agents():
        if common.identity(agent).get("mode") != "subagent":
            continue
        head, text = common.assemble_agent(agent)
        tools = [t for category in head.get("tools", []) for t in CLAUDE_TOOLS.get(category, [])]
        write(f".claude/agents/{head['name']}.md", (
            f"---\nname: {head['name']}\ndescription: {head['description']}\n"
            f"tools: {', '.join(tools)}\nmodel: {models.get(head.get('model', 'standard'), 'inherit')}\n---\n"
            f"<!-- {WARNING} -->\n\n{text}"
        ))
    link = WS / ".claude" / "skills"
    if link.is_symlink() or not link.exists():
        if link.is_symlink():
            link.unlink()
        link.symlink_to("../.agents/skills", target_is_directory=True)
        print("  .claude/skills -> ../.agents/skills")
    write(".mcp.json", json.dumps({"mcpServers": mcp_json(servers, with_type=True)}, indent=2) + "\n")
    # Permissions and journal hooks: source in harness/claude/settings.json (core, or the workspace's override).
    settings = common.find("harness/claude/settings.json")
    if settings:
        write(".claude/settings.json", settings.read_text(encoding="utf-8"))


def generate_pi(servers):
    write(".pi/mcp.json", json.dumps({"mcpServers": mcp_json(servers, with_type=False)}, indent=2) + "\n")


def toml_list(values):
    return "[" + ", ".join(json.dumps(v) for v in values) + "]"


def generate_codex(servers):
    lines = [f"# {WARNING}",
             "# Project file read by Codex once the project is trusted; otherwise copy it into ~/.codex/config.toml.", ""]
    for name, s in servers.items():
        lines.append(f"[mcp_servers.{name}]")
        if "url" in s:
            lines.append(f"url = {json.dumps(s['url'])}")
        else:
            lines.append(f"command = {json.dumps(s['command'])}")
            lines.append(f"args = {toml_list(s.get('args', []))}")
        lines.append("")
    write(".codex/config.toml", "\n".join(lines))


def generate_hermes(servers):
    lines = [f"# {WARNING}", "# Merge into ~/.hermes/config.yaml.", "", "mcp_servers:" + ("" if servers else " {}")]
    for name, s in servers.items():
        lines.append(f"  {name}:")
        if "url" in s:
            lines.append(f"    url: {json.dumps(s['url'])}")
        else:
            lines.append(f"    command: {json.dumps(s['command'])}")
            lines.append(f"    args: {toml_list(s.get('args', []))}")
    lines += [
        "",
        "skills:",
        "  # Skills Hermes writes itself go through the extensions cycle (extensions/drafts/).",
        f"  create_dir: {json.dumps(str(WS / 'extensions' / 'drafts'))}",
        "  write_approval: true",
        "",
    ]
    write("state/hermes.yaml", "\n".join(lines))


def mcp_servers():
    return {n: s for n, s in common.read_toml("mcp/servers.toml").items()
            if isinstance(s, dict) and ("url" in s or "command" in s)}


def check(servers):
    """Every active extension is in the registry, and every registered extension still exists.

    Active extensions: the skills of every layer and the MCP servers of mcp/servers.toml. The registry
    (extensions/registry.toml) is merged across layers: the workspace's lists the core skills and the user's
    own, each module registers its own. An internal entry (no `location`) must match a skill or a server; an
    external entry (`location`, relative to the workspace) must point to an existing path."""
    registry = {n: e for n, e in common.read_toml("extensions/registry.toml").items() if isinstance(e, dict)}
    found = skills()
    internal = {n: e for n, e in registry.items() if "location" not in e}
    missing = sorted((set(found) | set(servers)) - set(internal))
    orphans = sorted(n for n, e in internal.items()
                     if (e.get("form") == "skill" and n not in found) or (e.get("form") == "mcp" and n not in servers))
    orphans += sorted(n for n, e in registry.items()
                      if "location" in e and not (WS / Path(e["location"]).expanduser()).exists())
    for name in missing:
        print(f"  ! {name} is active but missing from extensions/registry.toml")
    for name in orphans:
        print(f"  ! {name} is in the registry but cannot be found")
    if not missing and not orphans:
        print("  registry consistent")
    return not missing and not orphans


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    servers = mcp_servers()
    if args.check:
        sys.exit(0 if check(servers) else 1)
    harness = common.read_toml("harness/harness.toml")
    print("The Rule:")
    generate_rule()
    print("Skills:")
    link_skills(skills())
    print("Claude Code:")
    generate_claude(harness, servers)
    print("pi:")
    generate_pi(servers)
    print("Codex:")
    generate_codex(servers)
    print("Hermes:")
    generate_hermes(servers)
    print("Registry:")
    check(servers)


if __name__ == "__main__":
    main()
