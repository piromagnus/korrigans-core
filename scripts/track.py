#!/usr/bin/env python3
"""The watchtower: follow the korrigans without opening their conversation.

    korrigans track               one line per running or recent task: rank, time, last step, watch verdict
    korrigans track --follow      the same, refreshed every 10 seconds (Ctrl+C to quit)
    korrigans track T-0003        detail of one task: progress, advice, attempts, end of the trace

korrigans run keeps state/execution/<id>.json and the live note Watchtower.md up to date (both derived and
git-ignored). The korrigan writes its progress in tasks/<id>/progress.md.
"""
import argparse
import fcntl
import json
import os
import sys
import tempfile
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

STATE = common.WS / "state" / "execution"
NOTE = common.WS / "Watchtower.md"


def now():
    return datetime.now().isoformat(timespec="seconds")


LOCK_FILE = common.WS / "state" / "execution" / ".lock"


def write_state(ident, **fields):
    """Update the run state of a task, then the Watchtower note."""
    STATE.mkdir(parents=True, exist_ok=True)
    with open(LOCK_FILE, "a") as lock_f:
        fcntl.flock(lock_f, fcntl.LOCK_EX)
        try:
            path = STATE / f"{ident}.json"
            state = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"id": ident}
            state.update(fields, updated=now())
            tmp = tempfile.NamedTemporaryFile("w", dir=STATE, delete=False, encoding="utf-8")
            try:
                tmp.write(json.dumps(state, ensure_ascii=False, indent=1))
                tmp.flush()
                os.fsync(tmp.fileno())
                tmp.close()
                os.replace(tmp.name, path)
            except Exception:
                if os.path.exists(tmp.name):
                    os.unlink(tmp.name)
                raise
            try:
                write_note()
            except OSError:
                pass
            return state
        finally:
            fcntl.flock(lock_f, fcntl.LOCK_UN)


def states():
    return [json.loads(f.read_text(encoding="utf-8")) for f in sorted(STATE.glob("T-*.json"))] if STATE.exists() else []


def last_step(folder):
    path = Path(folder) / "progress.md"
    if not folder or not path.exists():
        return ""
    lines = [l.strip("- ").strip() for l in path.read_text(encoding="utf-8").splitlines() if l.strip().startswith("-")]
    return lines[-1] if lines else ""


def duration(start):
    if not start:
        return ""
    minutes = int((datetime.now() - datetime.fromisoformat(start)).total_seconds() // 60)
    return f"{minutes // 60} h {minutes % 60:02d}" if minutes >= 60 else f"{minutes} min"


def rows():
    result = []
    for s in states():
        verdict = s.get("verdict") or {}
        result.append({
            "id": s["id"], "link": s.get("link", ""), "title": s.get("title", ""), "state": s.get("state", ""),
            "rank": f"{s.get('rank', '')} ({s.get('step', '?')}/{s.get('steps', '?')})",
            "harness": s.get("harness", ""),
            "time": duration(s.get("attempt_start")) if s.get("state") == "running" else "",
            "step": last_step(s.get("folder", "")),
            "watch": f"{verdict.get('verdict', '')}: {verdict.get('reason', '')}" if verdict else "",
        })
    return result


def write_note():
    lines = ["---", 'summary: "What the korrigans are doing now; regenerated by korrigans run, do not edit."', "---",
             "# Watchtower", "", f"Updated {now().replace('T', ' at ')}. Detail: `korrigans track <id>`.", "",
             "| Task | State | Rank | Harness | Since | Last step | Watch |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows():
        clean = [str(c).replace("|", "/").replace("\n", " ") for c in
                 (r["title"], r["state"], r["rank"], r["harness"], r["time"], r["step"], r["watch"])]
        task = f"[[{r['link']}\\|{r['id']}]] {clean[0]}" if r["link"] else f"{r['id']} {clean[0]}"
        lines.append("| " + " | ".join([task] + clean[1:]) + " |")
    content = "\n".join(lines) + "\n"
    tmp = tempfile.NamedTemporaryFile("w", dir=NOTE.parent, delete=False, encoding="utf-8")
    try:
        tmp.write(content)
        tmp.flush()
        os.fsync(tmp.fileno())
        tmp.close()
        os.replace(tmp.name, NOTE)
    except Exception:
        if os.path.exists(tmp.name):
            os.unlink(tmp.name)
        raise


def show():
    found = rows()
    if not found:
        print("No tracked run.")
        return
    for r in found:
        print(f"{r['id']}  {r['state']:<18}{r['rank']:<28}{r['harness']:<8}{r['time']:<9}{r['title'][:40]}")
        if r["step"]:
            print(f"        step: {r['step'][:100]}")
        if r["watch"]:
            print(f"        watch: {r['watch'][:100]}")


def detail(ident):
    s = next((x for x in states() if x["id"] == ident), None)
    if not s:
        sys.exit(f"No tracked run for {ident}")
    folder = Path(s.get("folder", ""))
    print(json.dumps({k: v for k, v in s.items() if k != "folder"}, ensure_ascii=False, indent=1))
    for name, n in (("progress.md", 15), ("advice.md", 12), ("attempts.md", 20)):
        path = folder / name
        if path.exists():
            print(f"\n--- {name} (end)\n" + "\n".join(path.read_text(encoding="utf-8").splitlines()[-n:]))
    traces = sorted(folder.glob("trace-*.log"), key=lambda p: p.stat().st_mtime)
    if traces:
        print(f"\n--- {traces[-1].name} (end)\n"
              + "\n".join(traces[-1].read_text(encoding="utf-8", errors="replace").splitlines()[-15:]))


def main():
    p = argparse.ArgumentParser(prog="korrigans track", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("id", nargs="?")
    p.add_argument("--follow", action="store_true", help="refresh every 10 seconds")
    args = p.parse_args()
    if args.id:
        detail(args.id)
        return
    try:
        while True:
            if args.follow:
                print("\033[2J\033[H", end="")
            show()
            if not args.follow:
                return
            time.sleep(10)
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
